#!/usr/bin/env node
'use strict';
const fs=require('node:fs');const path=require('node:path');const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'blazarlab.js'),'utf8');
const css=fs.readFileSync(path.join(root,'styles.css'),'utf8');
const changelog=fs.readFileSync(path.join(root,'CHANGELOG.md'),'utf8');
const readme=fs.readFileSync(path.join(root,'README.md'),'utf8');
const version=fs.readFileSync(path.join(root,'VERSION'),'utf8').trim();
assert.equal(version,'1.3.40');
assert.match(html,/id="secretBackgroundPicker"(?! hidden)/,'controles visuais ficam visíveis desde o carregamento');
assert.match(html,/data-accent-choice="blue" aria-pressed="true"><span class="palette-swatch palette-swatch-blue"/,'Azul original é o fallback declarado na marcação');
assert.match(html,/data-accent-choice="rose" aria-pressed="false"><span class="palette-swatch palette-swatch-rose"/,'Rosa cósmico está imediatamente disponível');
assert.match(html,/aria-pressed="false" class="theme-button secret-sound-toggle" id="secretSoundToggle"/,'sons iniciam desligados por escolha segura');
assert.match(js,/secretPaletteUnlocked=true/,'recursos visuais disponíveis sem sequência de desbloqueio');
assert.match(js,/root\.dataset\.secretUnlocked='true'/,'a interface anuncia o recurso visual como disponível');
assert.doesNotMatch(js,/realThemeSwitches<13/,'a sequência antiga de desbloqueio foi removida');
assert.match(js,/localStorage\.setItem\('blazarlab-accent-palette',selected\)/,'a paleta escolhida é lembrada entre visitas');
assert.match(js,/localStorage\.setItem\('blazarlab-background-mode',selected\)/,'o fundo escolhido é lembrado entre visitas');
assert.match(js,/const AudioContextConstructor=window\.AudioContext\|\|window\.webkitAudioContext/,'sons são sintetizados localmente sem arquivo externo');
assert.match(js,/setSoundToggleState\(false\)/,'som não começa automaticamente');
assert.match(js,/if\(!secretPaletteUnlocked\|\|!interactionSoundEnabled\|\|event\.isTrusted===false\)return/,'som só toca após ativação voluntária do usuário');
assert.match(js,/control\.closest\('\.chart-frame,\.chart-tools,\.band-toggle-legend,\.accessible-table-scroll'\)/,'interações frequentes com gráficos/tabelas não disparam sons repetitivos');
assert.match(css,/\.secret-palette-options\{display:grid;grid-template-columns:repeat\(2,minmax\(0,1fr\)\)/,'seletor de paleta tem duas opções responsivas');
assert.match(css,/\.secret-sound-toggle\[aria-pressed="true"\]/,'estado sonoro ligado é visível');
assert.match(changelog,/controles de paleta, fundos astronômicos e som de interação ficam disponíveis desde a primeira visita/i);
assert.match(readme,/som de interação continua opcional/i);
console.log('OK: paleta/fundos disponíveis no primeiro acesso, preferência persistente e áudio opt-in.');
